import { describe, expect, test } from 'bun:test';
import { calcStreak } from '../../src/core/streak.ts';

describe('calcStreak', () => {
  test('空配列は0', () => {
    expect(calcStreak([], '2024-03-10')).toBe(0);
  });
  test('今日のみで1', () => {
    expect(calcStreak(['2024-03-10'], '2024-03-10')).toBe(1);
  });
  test('今日が未チェックで昨日・一昨日なら2', () => {
    expect(calcStreak(['2024-03-09', '2024-03-08'], '2024-03-10')).toBe(2);
  });
  test('1日空けたら止まる（空いた前の連続は数えない）', () => {
    expect(calcStreak(['2024-03-10', '2024-03-08', '2024-03-07'], '2024-03-10')).toBe(1);
  });
  test('昨日も未チェックなら0', () => {
    expect(calcStreak(['2024-03-08'], '2024-03-10')).toBe(0);
  });
  test('月をまたぐ（うるう年の2月末）', () => {
    expect(calcStreak(['2024-03-01', '2024-02-29', '2024-02-28'], '2024-03-01')).toBe(3);
  });
  test('年をまたぐ', () => {
    expect(calcStreak(['2024-01-01', '2023-12-31', '2023-12-30'], '2024-01-01')).toBe(3);
  });
  test('うるう日を数える', () => {
    expect(calcStreak(['2024-03-01', '2024-02-29'], '2024-03-01')).toBe(2);
  });
  test('未来日付だけなら0', () => {
    expect(calcStreak(['2024-03-11', '2024-03-12'], '2024-03-10')).toBe(0);
  });
  test('未来日付は数えない', () => {
    expect(calcStreak(['2024-03-11', '2024-03-10', '2024-03-09'], '2024-03-10')).toBe(2);
  });
  test('重複した日付は1日と数える', () => {
    expect(calcStreak(['2024-03-10', '2024-03-10', '2024-03-09'], '2024-03-10')).toBe(2);
  });
  test('順不同の入力でも数えられる', () => {
    expect(calcStreak(['2024-03-08', '2024-03-10', '2024-03-09'], '2024-03-10')).toBe(3);
  });
});
