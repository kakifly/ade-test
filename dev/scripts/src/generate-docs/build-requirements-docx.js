/**
 * 見出し行付きの罫線表を作る。セルの改行（\n）は段落に分ける。
 * @param widths 列ごとの幅（DXA）
 * @param header 見出し行の各列の文字
 * @param rows データ行（各行は列ごとの文字の配列）
 * @returns 表（Table）
 */
function table(widths, header, rows) {
  const mk = (text, w, head) => new TableCell({
    width: { size: w, type: WidthType.DXA },
    borders: BORDERS,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    shading: head ? { fill: 'DCE6F1', type: ShadingType.CLEAR, color: 'auto' } : undefined,
    children: String(text).split('\n').map((line) => new Paragraph({ children: [t(line, { size: 20, bold: head })] })),
  });
  return new Table({
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({ tableHeader: true, children: header.map((c, i) => mk(c, widths[i], true)) }),
      ...rows.map((r) => new TableRow({ cantSplit: true, children: r.map((c, i) => mk(c, widths[i], false)) })),
    ],
  });
}
